  if (from === 'Uppal' && FARE_FROM_UPPAL[to]) {
    return FARE_FROM_UPPAL[to];
  }
  if (to === 'Uppal' && FARE_FROM_UPPAL[from]) {
    return FARE_FROM_UPPAL[from];
  }
  // Sensible default fallback based on rough distance
